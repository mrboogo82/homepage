#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""면 글(text/<base>-p<N>.txt)에서 가림 후보(회사·기관·주소·번호·따옴표 안 이름)를 뽑아 보여 준다.
    python3 cands.py <base> <pno>"""
import re, sys, os
ROOT = '/home/claude/jumun2'
base, pno = sys.argv[1], sys.argv[2]
t = open(f'{ROOT}/text/{base}-p{pno}.txt', encoding='utf-8').read()
t1 = re.sub(r'\s+', ' ', t)
pats = {
 'corp': r'(?:주식회사|유한회사|합자회사|합명회사|유한책임회사|재단법인|사단법인|학교법인|의료법인|사회복지법인|농업회사법인|영농조합법인|㈜|\(주\))\s*[가-힣A-Za-z0-9·&]{1,20}|[가-힣A-Za-z0-9·&]{1,20}\s*(?:주식회사|유한회사|㈜|\(주\))',
 'org': r'[가-힣A-Za-z0-9·&]{2,25}(?:산학협력단|대학교|대학|병원|연구소|연구원|협회|조합|센터|공단|공사|재단|진흥원|평가원|기술원|시험원|학회|은행|보험|증권|카드|의원|학교|유치원|어린이집|법무법인|법률사무소|세무법인|회계법인|특허법인)',
 'addr': r'(?:서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충청|충북|충남|전라|전북|전남|경상|경북|경남|제주)[가-힣]*(?:특별시|광역시|특별자치시|특별자치도|도|시)?\s*[가-힣]{1,6}(?:시|군|구)?\s*[가-힣0-9]{1,10}(?:동|읍|면|로|길|리)\s*[0-9\-번지]*(?:\s*[가-힣0-9()]{0,12}(?:호|층|동))?',
 'lot': r'[가-힣]{1,8}(?:동|리|가)\s*(?:산\s*)?\d{1,5}(?:-\d{1,4})?(?:번지)?\s*(?:[가-힣]{1,3}\s*\d{1,6}(?:\.\d+)?\s*㎡)?',
 'num': r'\d{6}-\d{7}|\d{3}-\d{2}-\d{5}|0\d{1,2}-\d{3,4}-\d{4}|\d{2,3}[가-힣]\s?\d{4}|\d{3,6}-\d{2,6}-\d{2,8}',
 'quote': r"'[^']{2,60}'|\"[^\"]{2,60}\"|「[^」]{2,60}」|『[^』]{2,60}』|‘[^’]{2,60}’|“[^”]{2,60}”",
 'role': r'(?:원고|피고|신청인|피신청인|채권자|채무자|소외|대표이사|대표자|연구책임자|증인|참가인|선정자|망|피고인|대리인|변호사|담당변호사|소송수행자|이사|감사|직원|교수|연구원)\s+[가-힣]{2,4}(?=[\s,.)(은는이가을를의와과에도]|$)',
}
for k, p in pats.items():
    ms = sorted(set(m.group(0).strip() for m in re.finditer(p, t1)))
    if ms:
        print(f'[{k}]')
        for m in ms:
            print('   ', m)
